import { test, expect } from '@playwright/test'
import { mkdir, readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { productPage } from './product-harness.mjs'
import { portfolioFixture } from '../api/portfolio-fixture.mjs'

test.use({ ignoreHTTPSErrors: true, locale: 'en-US', timezoneId: 'America/New_York' })
for (const width of [1440, 390]) {
  test(`REPO-007 saves ordered supplier renewal columns, shares to approvers, pins personally and exports only their visible rows at ${width}px`, async ({ page }) => {
    const p = await productPage(page, { width, bindings: { TEST_NOW: String(Date.parse('2026-10-17T12:00:00Z')) } })
    try {
      const tag = `Views-${width}`, ids = await portfolioFixture(p.owner, tag)
      const approver = await p.h.invite(`saved-approver-${width}@example.test`, 'approver')
      await page.goto(p.origin + '/app#agreements')
      const panel = page.getByRole('region', { name: 'Saved repository views', exact: true })
      const screenshot = async (name: string) => {
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
        if (process.env.LOCKET_SCREENSHOTS) {
          await mkdir(process.env.LOCKET_SCREENSHOTS, { recursive: true })
          await panel.scrollIntoViewIfNeeded()
          await page.screenshot({ path: join(process.env.LOCKET_SCREENSHOTS, `${width}-repo-007-${name}.png`), fullPage: true })
        }
      }
      await panel.getByRole('button', { name: 'New view', exact: true }).click()
      await panel.getByLabel('View name', { exact: true }).fill('Supplier renewals next quarter')
      await panel.getByLabel('View query', { exact: true }).fill(tag)
      for (const [index, field, operator, value] of [[1, 'type', 'eq', 'supplier'], [2, 'current_term_end', 'gte', '2027-01-01'], [3, 'current_term_end', 'lte', '2027-03-31']] as const) {
        await panel.getByRole('button', { name: 'Add filter', exact: true }).click()
        await panel.getByLabel(`Filter field ${index}`, { exact: true }).selectOption(field)
        await panel.getByLabel(`Filter operator ${index}`, { exact: true }).selectOption(operator)
        await panel.getByLabel(`Filter value ${index}`, { exact: true }).fill(value)
      }
      await panel.getByLabel('Sort field', { exact: true }).selectOption('value')
      await panel.getByLabel('Sort direction', { exact: true }).selectOption('desc')
      await panel.getByLabel('Shared with approver', { exact: true }).check()
      await panel.getByRole('button', { name: 'Move Value (USD) up', exact: true }).click()
      await panel.getByRole('button', { name: 'Apply view', exact: true }).click()
      await expect(panel.getByRole('status')).toHaveText('2 agreements you can access.')
      await expect(panel.locator('thead th')).toHaveText(['Value (USD)', 'Agreement', 'Owner', 'Notice deadline'])
      await expect(panel.locator('tbody tr').first().locator('td')).toHaveCount(4)
      await expect(panel.getByRole('table')).toContainText('2026-12-30')
      await screenshot('definition-preview')
      const response = page.waitForResponse(r => r.url() === p.origin + '/api/locket/commands' && r.request().method() === 'POST')
      await panel.getByRole('button', { name: 'Save view', exact: true }).click()
      const saved = await (await response).json()
      expect(saved.ok, JSON.stringify(saved.error)).toBe(true)
      const id = saved.result.id
      await expect(panel.getByRole('button', { name: 'Pin view', exact: true })).toBeVisible()
      await panel.getByRole('button', { name: 'Pin view', exact: true }).click()
      await expect(panel.getByRole('button', { name: 'Unpin view', exact: true })).toBeVisible()
      await screenshot('saved-pinned')
      await page.context().clearCookies()
      await page.context().addCookies(approver.cookie.split('; ').map((pair: string) => {
        const i = pair.indexOf('=')
        return { name: pair.slice(0, i), value: pair.slice(i + 1), url: p.origin, secure: true, httpOnly: true, sameSite: 'Lax' as const }
      }))
      await page.reload()
      await panel.getByLabel('Saved view', { exact: true }).selectOption(id)
      await panel.getByRole('button', { name: 'Open saved view', exact: true }).click()
      await expect(panel.getByRole('status')).toHaveText('1 agreement you can access.')
      await expect(panel.getByRole('table')).toContainText(`old agreement ${tag}`)
      await expect(panel.getByRole('table')).not.toContainText(`hidden agreement ${tag}`)
      await expect(panel.getByRole('table')).toContainText('$100,000.25')
      await expect(panel.getByRole('button', { name: 'Pin view', exact: true })).toBeVisible()
      await screenshot('approver-results')
      const downloaded = page.waitForEvent('download')
      await panel.getByRole('button', { name: 'Export view CSV', exact: true }).click()
      const path = await (await downloaded).path()
      const csv = await readFile(path!, 'utf8')
      expect(csv).toContain('"Value (USD)","Agreement","Owner","Notice deadline"')
      expect(csv).toContain('"$100,000.25"')
      expect(csv).toContain(`old agreement ${tag}`)
      expect(csv).not.toContain(`hidden agreement ${tag}`)
      expect(csv).toContain('2026-12-30')
      const result = await (await approver.request('/api/locket/repository?viewId=' + id)).json()
      expect(result.rows.map((row: any) => row.id)).toEqual([ids.old])
      await screenshot('exported')
    } finally { await p.close() }
  })
}

for (const width of [1440, 390]) test(`REPO-005 defines typed fields, blocks incomplete approval, saves metadata views and accepts cited family values at ${width}px`, async ({ page }) => {
  const { metadataPage } = await import('./metadata-page.mjs')
  const { fieldSpec, metadataText, metadataAgreement, customKey } = await import('../api/custom-metadata-fixture.mjs')
  const { pdf } = await import('../api/files.mjs')
  const { randomUUID } = await import('node:crypto')
  const p = await metadataPage(page, width)
  const tag = randomUUID().slice(0, 6)
  const names = { yes: `Data processing ${tag}`, cost: `Cost center ${tag}` }
  const shot = async (name: string) => {
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
    if (process.env.LOCKET_SCREENSHOTS) {
      await mkdir(process.env.LOCKET_SCREENSHOTS, { recursive: true })
      await page.screenshot({ path: join(process.env.LOCKET_SCREENSHOTS, `${width}-REPO-005-${name}.png`), fullPage: true })
    }
  }
  const runUi = async (action: () => Promise<unknown>, error?: string) => {
    const response = page.waitForResponse(r => r.url() === p.origin + '/api/locket/commands' && r.request().method() === 'POST')
    await action()
    const body = await (await response).json()
    if (error) expect(body.error?.code, JSON.stringify(body)).toBe(error)
    else expect(body.ok, JSON.stringify(body.error)).toBe(true)
    return body.result
  }
  try {
    let initial = await p.owner.state()
    for (const f of initial.customFields) if (JSON.parse(f.required_stages).length) await p.owner.command('field.save', { id: f.id, version: f.version, name: f.name, kind: f.kind, agreementTypes: JSON.parse(f.agreement_types), helpText: f.help_text, requiredStages: [], editRoles: JSON.parse(f.edit_roles), options: JSON.parse(f.options) })
    await page.goto(p.origin + '/app#library'); await page.reload()
    const manager = page.getByRole('region', { name: 'Custom metadata settings', exact: true })
    await manager.getByText('Manage custom fields', { exact: true }).click()
    for (const [name, kind] of [[names.yes, 'yes_no'], [names.cost, 'pick_list']]) {
      await manager.getByLabel('Field to configure', { exact: true }).selectOption('')
      await manager.getByLabel('Field name', { exact: true }).fill(name)
      await manager.getByLabel('Field type', { exact: true }).selectOption(kind)
      await manager.getByLabel('Help text', { exact: true }).fill('Record the agreed processing requirements.')
      for (const input of await manager.locator('input[name="agreementType"]').all()) await input.setChecked(await input.getAttribute('value') === 'other')
      if (kind === 'pick_list') {
        await manager.getByLabel('Pick list options', { exact: true }).fill('Operations\nFinance')
        await manager.locator('input[name="requiredStage"][value="approved"]').check()
      }
      await runUi(() => manager.getByRole('button', { name: 'Create field', exact: true }).click())
      await expect(manager.getByRole('button', { name: 'Save field changes', exact: true })).toBeVisible()
    }
    await shot('owner-definitions')
    let state = await p.owner.state()
    const yes = state.customFields.find((f: any) => f.name === names.yes).id
    const cost = state.customFields.find((f: any) => f.name === names.cost).id
    const extra: Record<string, string> = {}
    for (const [name, kind] of [['Memo','text'],['Seats','number'],['Budget','money'],['Review day','date'],['Steward','person'],['Affiliate','counterparty']]) extra[kind] = (await p.owner.command('field.save', fieldSpec(`${name} ${tag}`, kind))).id
    const reference = await p.owner.command('request.create', { title: `Reference ${tag}`, type: 'other', party: { name: `Harbour Processing ${tag}`, kind: 'supplier' } })
    state = await p.owner.state()
    const partyId = state.agreements.find((a: any) => a.id === reference.id).party_id
    await page.goto(p.origin + '/app#new'); await page.reload()
    await page.getByLabel('Agreement title *', { exact: true }).fill(`Processing services ${tag}`)
    await page.getByLabel('Request type *', { exact: true }).selectOption('other')
    const intake = page.locator('.lk-intake-form')
    await intake.getByLabel(names.yes, { exact: true }).selectOption('true')
    await intake.getByLabel(`Memo ${tag}`, { exact: true }).fill('Processing review')
    await intake.getByLabel(`Seats ${tag}`, { exact: true }).fill('25')
    await intake.getByLabel(`Budget ${tag} (USD)`, { exact: true }).fill('1200.50')
    await intake.getByLabel(`Review day ${tag}`, { exact: true }).fill('2027-02-01')
    await intake.getByLabel(`Steward ${tag}`, { exact: true }).selectOption(state.actor.id)
    await intake.getByLabel(`Affiliate ${tag}`, { exact: true }).selectOption(partyId)
    await page.getByLabel('Attach draft', { exact: true }).check()
    await page.getByLabel('Draft (PDF or DOCX)', { exact: true }).setInputFiles({ name: 'Processing agreement.pdf', mimeType: 'application/pdf', buffer: pdf(metadataText) })
    await page.getByLabel('Text (optional for PDF)', { exact: true }).fill(metadataText)
    await shot('typed-intake')
    const created = await runUi(() => page.getByRole('button', { name: 'Create request', exact: true }).click())
    await expect(page).toHaveURL(new RegExp(`agreement/${created.id}`))
    await page.goto(p.origin + `/app#agreement/${created.id}/versions`)
    await runUi(() => page.getByRole('button', { name: 'Submit for review', exact: true }).click())
    await page.goto(p.origin + `/app#agreement/${created.id}/approvals`)
    await runUi(() => page.getByRole('button', { name: 'Record decision', exact: true }).click(), 'FIELDS')
    await expect(page.getByRole('alert')).toContainText(names.cost)
    await shot('approval-refused')
    await page.goto(p.origin + `/app#agreement/${created.id}/details`)
    const metadata = page.getByRole('region', { name: 'Agreement custom metadata', exact: true }).locator('form').first()
    await metadata.getByLabel(names.cost, { exact: true }).selectOption('Operations')
    await runUi(() => metadata.getByRole('button', { name: 'Save custom metadata', exact: true }).click())
    await expect(metadata.getByLabel(names.cost, { exact: true })).toHaveValue('Operations')
    await shot('agreement-values')
    await page.goto(p.origin + `/app#agreement/${created.id}/approvals`)
    await runUi(() => page.getByRole('button', { name: 'Record decision', exact: true }).click())
    await expect(page.getByRole('heading', { name: 'All decisions' })).toBeVisible()
    await shot('approval-complete')
    await page.goto(p.origin + '/app#agreements')
    const panel = page.getByRole('region', { name: 'Saved repository views', exact: true })
    await panel.getByRole('button', { name: 'New view', exact: true }).click()
    await panel.getByLabel('View name', { exact: true }).fill(`Processing metadata ${tag}`)
    for (const [index, field, filter] of [[1, yes, 'yes'], [2, cost, 'Operations']] as const) {
      await panel.getByRole('button', { name: 'Add filter', exact: true }).click()
      await panel.getByLabel(`Filter field ${index}`, { exact: true }).selectOption(customKey(field))
      await panel.getByLabel(`Filter value ${index}`, { exact: true }).fill(filter)
    }
    await panel.getByLabel('Sort field', { exact: true }).selectOption(customKey(cost))
    for (const name of ['Value (USD)','Owner','Notice deadline']) await panel.getByLabel(`Column ${name}`, { exact: true }).uncheck()
    for (const name of [names.cost,names.yes]) await panel.getByLabel(`Column ${name}`, { exact: true }).check()
    await panel.getByRole('button', { name: `Move ${names.yes} up`, exact: true }).click()
    await panel.getByRole('button', { name: 'Apply view', exact: true }).click()
    await expect(panel.getByRole('status')).toHaveText('1 agreement you can access.')
    await expect(panel.locator('thead th')).toHaveText(['Agreement',names.yes,names.cost])
    await expect(panel.getByRole('table')).toContainText('Operations')
    await expect(panel.getByRole('table')).toContainText('yes')
    const saved = await runUi(() => panel.getByRole('button', { name: 'Save view', exact: true }).click())
    const download = page.waitForEvent('download')
    await panel.getByRole('button', { name: 'Export view CSV', exact: true }).click()
    const csv = await readFile((await (await download).path())!, 'utf8')
    expect(csv).toContain(`"Agreement","${names.yes}","${names.cost}"`)
    expect(csv).toContain(`Processing services ${tag}`)
    await shot('custom-saved-view')
    const reports = page.getByRole('region', { name: 'Custom reports', exact: true })
    await reports.getByText('Schedule a report', { exact: true }).click()
    await reports.getByLabel('Report name', { exact: true }).fill(`Processing by cost center ${tag}`)
    await reports.getByLabel('Saved view', { exact: true }).selectOption(saved.id)
    await reports.getByLabel('Group by', { exact: true }).selectOption(customKey(cost))
    await reports.locator('input[type="datetime-local"]').fill('2027-06-01T09:00')
    await runUi(() => reports.getByRole('button', { name: 'Schedule report', exact: true }).click())
    await reports.getByRole('button', { name: 'Open report', exact: true }).last().click()
    await expect(page.getByRole('region', { name: 'Report preview', exact: true })).toContainText('Operations')
    await shot('custom-report')
    const child = await metadataAgreement(p.owner, { title: `Processing amendment ${tag}`, parentId: created.id, values: { [yes]: true, [cost]: 'Finance' } })
    await page.goto(p.origin + `/app#agreement/${child.id}/details`); await page.reload()
    const proposalForm = page.getByRole('region', { name: 'Agreement custom metadata', exact: true }).locator('details')
    await proposalForm.locator('summary').click()
    await proposalForm.getByLabel(names.cost, { exact: true }).selectOption('Operations')
    await proposalForm.getByLabel('Exact words from the current document', { exact: true }).fill('Cost center: Operations.')
    await runUi(() => proposalForm.getByRole('button', { name: 'Prepare metadata proposal', exact: true }).click())
    await page.goto(p.origin + '/app#proposals')
    await expect(page.getByText('Review or correct proposed values', { exact: true })).toBeVisible()
    await shot('cited-proposal')
    await runUi(() => page.getByRole('button', { name: 'Record decision', exact: true }).click())
    await page.goto(p.origin + `/app#agreement/${created.id}/family`)
    await page.getByLabel('Confirmed source term', { exact: true }).selectOption({ label: (await page.getByLabel('Confirmed source term', { exact: true }).locator('option').allTextContents()).find(text => text.startsWith(names.cost))! })
    await runUi(() => page.getByRole('button', { name: 'Select governing term', exact: true }).click())
    await expect(page.locator(`[data-governing-key="${customKey(cost)}"]`)).toContainText('Operations')
    await expect(page.locator(`[data-governing-key="${customKey(cost)}"]`)).toContainText('Cost center: Operations.')
    await shot('cited-family')
    const imported = await p.owner.command('legacy.import', { title: `Historical processing ${tag}`, type: 'other', partyId, sourceSystem: 'Archive', sourceId: `synthetic-locket-${tag}`, file: { filename: 'legacy.pdf', mediaType: 'application/pdf', base64: pdf(metadataText + tag).toString('base64') }, text: metadataText, customValues: { [yes]: true, [cost]: 'Operations' } })
    const importedState = await p.owner.state()
    const importedVersion = importedState.agreements.find((a: any) => a.id === imported.id).current_version_id
    const start = metadataText.indexOf('Cost center')
    const proposal = await p.owner.command('proposal.prepare', { kind: 'custom_fields', payload: { agreementId: imported.id, versionId: importedVersion, values: { [cost]: 'Operations' }, citation: { quote: 'Cost center: Operations.', start, end: start + 'Cost center: Operations.'.length } }, evidence: ['Historical document passage'] })
    await p.owner.command('proposal.decide', { proposalId: proposal.id, decision: 'approve' })
    await page.goto(p.origin + `/app#agreement/${imported.id}/terms`); await page.reload()
    await expect(page.getByRole('table').first()).toContainText(names.cost)
    await expect(page.getByRole('table').first()).toContainText('Cost center: Operations.')
    await shot('confirmed-custom-term')
  } finally { await p.close() }
})
