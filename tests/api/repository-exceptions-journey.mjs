import {businessCommands} from './repository-policy-journey.mjs'
import assert from 'node:assert/strict'
import {file,pdf} from './files.mjs'

export async function repositoryExceptionsJourney(h){
 const now=Date.parse('2026-10-28T12:00:00Z');await h.setTime(now)
 const configure=async values=>h.owner.command('repository.access',{...(await h.owner.state()).repositoryPolicy,...values})
 await configure({enabled:false,grants:[],hiddenFields:[]})
 const requester=await h.invite('synthetic-locket-exception-requester@example.test','requester')
 const viewer=await h.invite('synthetic-locket-exception-viewer@example.test','viewer')
 const counsel=await h.invite('synthetic-locket-exception-counsel@example.test','counsel')
 const group=await h.owner.command('audience.save',{name:'Exception Sales',kind:'group',memberIds:[]})
 const create=(client,restricted=false)=>client.command('request.create',{title:'synthetic-locket-exception',type:'customer',restricted,value:'100',party:{name:'synthetic-locket-exception',kind:'customer'},text:'synthetic-locket-source',file:file('exception.pdf',pdf('synthetic-locket-source'))})
 const own=await create(requester),restricted=await create(h.owner,true)
 const row=async id=>(await h.owner.state()).agreements.find(a=>a.id===id)
 await configure({enabled:true,grants:[{audienceId:group.id,types:['customer'],departmentIds:[]}]})
 assert.ok(!(await requester.state()).agreements.some(a=>a.id===own.id))
 const share=async(client,id,person,extra={})=>client.command('access.exception',{agreementId:id,version:(await row(id)).version,operatorId:person.id,reason:'Temporary review',expiresAt:now+60_000,...extra})
 await share(counsel,own.id,requester)
 assert.ok((await requester.state()).agreements.some(a=>a.id===own.id),'exception overrides unmatched group grants')
 await share(h.owner,restricted.id,viewer)
 assert.ok(!(await viewer.state()).agreements.some(a=>a.id===restricted.id),'exception never bypasses restricted custody')
 await h.owner.command('access.set',{agreementId:restricted.id,operatorId:viewer.id,grant:'grant'})
 assert.ok((await viewer.state()).agreements.some(a=>a.id===restricted.id),'restricted and group authority are both required')
 await h.setTime(now+60_000)
 assert.ok(!(await requester.state()).agreements.some(a=>a.id===own.id),'share expires at the exact boundary')
 assert.ok(!(await viewer.state()).agreements.some(a=>a.id===restricted.id),'restricted grant does not preserve expired group exception')
 await requester.command('request.update',{agreementId:own.id,version:(await row(own.id)).version,title:'denied'},{error:'NOT_FOUND'})
 await h.setTime(now)
 await share(h.owner,own.id,requester,{revoke:true})
 assert.ok(!(await requester.state()).agreements.some(a=>a.id===own.id),'explicit revoke removes exception immediately')
 await h.owner.command('audience.save',{...group,name:'Exception Sales',kind:'group',memberIds:[requester.id,viewer.id]})
 await configure({hiddenFields:[{role:'',audienceId:group.id,fields:['value']}]})
 let a=await row(own.id)
 const submitted=await requester.command('agreement.hidden-value',{agreementId:a.id,version:a.version,value:'637281.43'})
 assert.deepEqual(submitted,{agreementId:a.id,submitted:true})
 assert.equal((await row(a.id)).value_cents,63728143,'hidden submitted value is stored')
 const hidden=await requester.state()
 assert.deepEqual(hidden.fieldAccess.hidden,['value'])
 assert.equal(hidden.agreements.find(x=>x.id===a.id).value_cents,undefined)
 assert.ok(!JSON.stringify(hidden).includes('637281'),'state never echoes hidden value')
 for(const type of await businessCommands())await requester.command(type,{},{error:'FIELD_ACCESS'})
 await viewer.command('agreement.hidden-value',{agreementId:a.id,version:(await row(a.id)).version,value:'2'},{error:'FORBIDDEN'})
 await requester.command('agreement.hidden-value',{agreementId:restricted.id,version:(await row(restricted.id)).version,value:'2'},{error:'NOT_FOUND'})
 const definition={query:'637281',filters:[],sort:{field:'title',direction:'asc'},columns:['title','value']}
 const params=new URLSearchParams({definition:JSON.stringify(definition)})
 const register=await(await requester.request('/api/locket/repository?'+params)).json()
 assert.equal(register.rows.length,0,'group-hidden value cannot match repository queries')
 const search=await(await requester.request('/api/locket/search?q=637281')).json()
 assert.ok(!JSON.stringify(search).includes('637281'))
 params.set('format','csv')
 assert.ok(!(await(await requester.request('/api/locket/repository?'+params)).text()).includes('637281'))
 params.delete('format');definition.query='';definition.sort.field='value';params.set('definition',JSON.stringify(definition))
 assert.equal((await requester.request('/api/locket/repository?'+params)).status,403,'group-hidden fields cannot influence sort order')
 await requester.command('agreement.hidden-value',{agreementId:a.id,version:a.version,value:'1'},{error:'STALE'})
 const report=await(await counsel.request('/api/locket/access-report?agreementId='+a.id)).json()
 assert.ok(report.readers.some(r=>r.id===requester.id&&r.reasons.includes('Agreement requester')&&r.reasons.includes('Repository grant: Exception Sales')))
 assert.ok(report.readers.some(r=>r.role==='owner'&&r.reasons.includes('owner role')))
 assert.ok(report.readers.some(r=>r.role==='counsel'&&r.reasons.includes('counsel role')))
 const refused=await viewer.request('/api/locket/access-report?agreementId='+a.id);assert.equal(refused.status,403)
 await counsel.command('agreement.legal-note',{agreementId:a.id,version:(await row(a.id)).version,body:'synthetic-locket-privileged-analysis'})
 assert.equal((await counsel.state()).privilegedNotes.find(n=>n.agreement_id===a.id).body,'synthetic-locket-privileged-analysis')
 assert.equal((await h.owner.state()).privilegedNotes.find(n=>n.agreement_id===a.id).body,'synthetic-locket-privileged-analysis')
 for(const client of [viewer,requester])assert.ok(!JSON.stringify(await client.state()).includes('synthetic-locket-privileged-analysis'))
 await requester.command('agreement.legal-note',{agreementId:a.id,version:(await row(a.id)).version,body:'denied'},{error:'FIELD_ACCESS'})
 await configure({hiddenFields:[]})
 await viewer.command('agreement.legal-note',{agreementId:a.id,version:(await row(a.id)).version,body:'denied'},{error:'FORBIDDEN'})
 await h.owner.command('audience.save',{id:group.id,version:2,name:'Exception Sales',kind:'group',memberIds:[]})
 const after=await(await counsel.request('/api/locket/access-report?agreementId='+a.id)).json()
 assert.ok(!after.readers.some(r=>r.id===requester.id),'report uses current membership')
 const audit=await(await h.owner.request('/api/locket/audit?format=csv')).text()
 assert.ok(audit.includes('before')&&audit.includes('after'),'existing before and after CSV proof remains')
 assert.ok(!audit.includes('synthetic-locket-privileged-analysis'),'note content stays out of audit exports')
}
