test('AGENT-003 missing acknowledgment alerts before deadline; uncertain sends never retry; changed source, role and late schedules refuse sending', async t=>{
  const key=webhookKey(),h=await installation({bindings:{NOTICE_RESEND_WEBHOOK_SECRET:key},mailResponse:m=>{if(m.attachments)return new Response('Provider outcome unknown',{status:500});return Response.json({id:crypto.randomUUID()})}})
  t.after(()=>h.close())
  const {agentFixture,approveAgent}=await import('./notice-fixture.mjs')
  const f=await agentFixture(h,'Uncertain',true),outside=await h.invite('notice-outside@example.test','viewer')
  const draft=await h.owner.command('notice.agent.prepare',{sourceId:f.sourceId}),due=Math.ceil((f.now+3600000)/3600000)*3600000
  const approval=await approveAgent(h.owner,draft.id,due)
  await h.setTime(due);await h.scheduled(due)
  let s=await h.owner.state();assert.equal(s.noticeDispatches.find(d=>d.notice_id===draft.id).status,'uncertain')
  await h.setTime(approval.watchAt);await h.scheduled(approval.watchAt)
  s=await h.owner.state();assert.ok(s.noticePlans.find(p=>p.id===draft.id).alert_at<f.deadline)
  assert.ok(s.noticePlans.some(p=>p.parent_notice_id===draft.id&&p.status==='draft'))
  await h.scheduled(approval.watchAt+3600000);assert.equal(h.mails.filter(m=>m.attachments).length,1)
  const hidden=await outside.state();assert.equal(hidden.noticeSources.length,0);assert.equal(hidden.noticePlans.length,0)
  // A changed decision makes the approved snapshot unusable.
  const second=await h.owner.command('notice.agent.prepare',{sourceId:f.sourceId})
  await approveAgent(h.owner,second.id,approval.watchAt+7200000)
  await h.owner.command('renewal.decide',{renewalId:f.renewalId,decision:'renew'})
  await h.setTime(approval.watchAt+7200000);await h.scheduled(approval.watchAt+7200000)
  s=await h.owner.state();assert.equal(s.noticePlans.find(p=>p.id===second.id).status,'cancelled')
  const approver=await h.invite('notice-approver@example.test','approver')
  const source=await h.owner.command('notice.source',{agreementId:f.agreementId,quote:'Give 60 days notice.'})
  const third=await h.owner.command('notice.agent.prepare',{sourceId:source.id})
  await approveAgent(approver,third.id,approval.watchAt+10800000)
  await h.owner.command('role.set',{operatorId:approver.id,role:'viewer'})
  await h.setTime(approval.watchAt+10800000);await h.scheduled(approval.watchAt+10800000)
  s=await h.owner.state();assert.equal(s.noticePlans.find(p=>p.id===third.id).status,'cancelled')
  const current=h.mails.filter(m=>m.attachments).length
  await h.setTime(f.deadline+1);await h.scheduled(f.deadline+1)
  assert.equal(h.mails.filter(m=>m.attachments).length,current)
})
