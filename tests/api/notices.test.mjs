test('RENEW-006 approved exact PDF/recipient email, signed provider events, retries, archive and manual certified-mail evidence', async t => {
  const key = webhookKey(), h = await installation({ bindings: { NOTICE_RESEND_WEBHOOK_SECRET: key } })
  t.after(() => h.close())
  const fixture = await noticeFixture(h.owner)
  const requester = await h.invite('sender@example.test', 'requester')
  const viewer = await h.invite('viewer@example.test', 'viewer')
  const agent = await h.invite('agent@example.test', 'agent')
  const n = await prepare(requester, fixture.renewalId)
  await requester.command('notice.email', { noticeId: n.id }, { error: 'STATUS' })
  const approval = await h.owner.command('notice.approve', { noticeId: n.id })
  let s = await h.owner.state()
  const letter = s.noticeLetters.find(l => l.id === n.id)
  const download = await requester.request(`/api/locket/files/${letter.artifact_id}`)
  const pdf = Buffer.from(await download.arrayBuffer())
  const digest = createHash('sha256').update(pdf).digest('hex')
  assert.equal(digest, approval.pdfDigest)
  assert.equal(digest, letter.sha256)
  assert.match(pdf.toString('latin1'), /December 31, 2026/)
  await viewer.command('notice.email', { noticeId: n.id }, { error: 'FORBIDDEN' })
  await agent.command('notice.email', { noticeId: n.id }, { error: 'FORBIDDEN' })
  const commandId = crypto.randomUUID(), mailCount = h.mails.length
  const results = await Promise.all([1, 2].map(() => requester.command('notice.email', { noticeId: n.id }, { commandId })))
  assert.deepEqual(results[0], results[1])
  assert.deepEqual(await requester.command('notice.email', { noticeId: n.id }, { commandId }), results[0])
  assert.equal(h.mails.length, mailCount + 1)
  const message = h.mails.at(-1)
  assert.deepEqual(message.to, [letter.recipient])
  assert.deepEqual(Buffer.from(message.attachments[0].content, 'base64'), pdf)
  assert.equal(message.attachments[0].content_type, 'application/pdf')
  s = await h.owner.state()
  const dispatch = s.noticeDispatches.find(d => d.notice_id === n.id)
  assert.equal(dispatch.status, 'accepted')
  assert.ok(dispatch.provider_message_id)
  assert.equal(dispatch.pdf_sha256, digest)
  assert.equal(s.notices.find(x => x.id === n.id).status, 'sent')
  assert.equal(s.noticeEvents.length, 0)
  const delivered = signedEvent(key, dispatch.provider_message_id)
  assert.equal((await postEvent(h, delivered)).status, 200)
  assert.equal((await postEvent(h, delivered)).status, 200)
  const tampered = { ...delivered, raw: delivered.raw.replace('email.delivered', 'email.bounced') }
  assert.equal((await postEvent(h, tampered)).status, 401)
  assert.equal((await postEvent(h, signedEvent(key, dispatch.provider_message_id, { id: delivered.headers['svix-id'], type: 'email.bounced' }))).status, 409)
  assert.equal((await postEvent(h, signedEvent(key, dispatch.provider_message_id, { to: 'other@example.test' }))).status, 409)
  assert.equal((await postEvent(h, signedEvent(key, dispatch.provider_message_id, { timestamp: 1 }))).status, 401)
  assert.equal((await postEvent(h, signedEvent(key, dispatch.provider_message_id, { type: 'email.bounced' }))).status, 200)
  s = await h.owner.state()
  assert.equal(s.noticeEvents.filter(e => e.status === 'delivered').length, 1)
  assert.equal(s.noticeEvents.filter(e => e.status === 'bounced').length, 1)
  assert.equal(s.audit.filter(e => e.action === 'notice.delivery').length, 2)
  const paper = await prepare(requester, fixture.renewalId, 'Cardinal Legal, 10 Main St, Raleigh NC')
  await h.owner.command('notice.approve', { noticeId: paper.id })
  await requester.command('notice.sent', { noticeId: paper.id, method: 'post', trackingNumber: '9400-1234-5678', sentAt: new Date(Date.now() - 60000).toISOString() })
  s = await h.owner.state()
  assert.equal(s.noticeTracking.find(r => r.id === paper.id).status, 'unconfirmed')
  await requester.command('notice.tracking', { noticeId: paper.id, trackingNumber: '9400-1234-5678', status: 'delivered', deliveredAt: new Date().toISOString(), detail: 'Carrier receipt uploaded by sender; signed for by reception.' })
  s = await h.owner.state()
  assert.equal(s.noticeTracking.find(r => r.id === paper.id).status, 'delivered')
  assert.equal(s.noticeEvents.find(r => r.notice_id === paper.id).source, 'manual')
  const archive = await (await h.owner.request('/api/locket/export')).json()
  assert.equal(archive.records.lk_notice_dispatches[0].pdf_sha256, digest)
  assert.equal(archive.records.lk_notice_events.length, 3)
  assert.deepEqual(Buffer.from(archive.files.find(f => f.id === letter.artifact_id).base64, 'base64'), pdf)
  assert.equal((await h.request('/api/locket/state')).status, 401)
})

