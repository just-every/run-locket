  const sends=h.mails.filter(m=>m.attachments)
  assert.equal(sends.length,1)
  assert.deepEqual(Buffer.from(sends[0].attachments[0].content,'base64'),bytes)
  assert.equal(createHash('sha256').update(bytes).digest('hex'),letter.sha256)
  s=await h.owner.state();const dispatch=s.noticeDispatches.find(d=>d.notice_id===n.id)
  assert.equal(dispatch.status,'accepted');assert.deepEqual(sends[0].to,[letter.recipient])
