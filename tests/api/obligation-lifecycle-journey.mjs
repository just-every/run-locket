import assert from 'node:assert/strict'
import { file, pdf } from './files.mjs'

// One manually cited lifecycle through the real command and state doors.
export async function obligationLifecycleJourney(h) {
  await h.setTime(Date.parse('2026-01-30T15:00:00Z'))
  const member = await h.invite('synthetic-locket-owner@example.test', 'requester')
  const stranger = await h.invite('synthetic-locket-other@example.test', 'requester')
  const annualOwner = await h.invite('synthetic-locket-annual-owner@example.test', 'counsel')
  const waiverOwner = await h.invite('synthetic-locket-waiver-owner@example.test', 'approver')
  const owner = h.owner, ownerId = (await owner.state()).actor.id
  const quote = 'Report monthly, audit quarterly and certify annually. The supplier must retain proof.'
  const a = await owner.command('legacy.import', { title: 'synthetic-locket-lifecycle', type: 'supplier', party: { name: 'synthetic-locket-lifecycle party', kind: 'supplier' }, sourceSystem: 'Shared drive', sourceId: 'synthetic-locket-lifecycle', restricted: true, signed: true, text: quote, file: file('synthetic-locket-lifecycle.pdf', pdf(quote)) })
  for (const person of [member, stranger, waiverOwner]) await owner.command('access.set', { agreementId: a.id, operatorId: person.id, grant: 'grant' })
  const add = async (description, extra = {}) => {
    const o = await owner.command('obligation.add', { agreementId: a.id, description, ownerId: member.id, dueDate: '2026-01-31', recurrence: 'none', citation: { quote }, ...extra })
    return o.id
  }
  await member.command('notification.preferences', { inApp: true, email: false, digest: false, timezone: 'America/New_York' })
  const monthly = await add('synthetic-locket-monthly', { recurrence: 'monthly', evidence: 'note' })
  const quarterly = await add('synthetic-locket-quarterly', { recurrence: 'quarterly', ownerId })
  const annual = await add('synthetic-locket-annual', { recurrence: 'annually', dueDate: '2024-02-29', ownerId: annualOwner.id })
  const waived = await add('synthetic-locket-waived', { evidence: 'file', ownerId: waiverOwner.id })
  const refused = await add('synthetic-locket-rejected')
  const pending = await add('synthetic-locket-proposed', { ownerId: stranger.id })
  assert.equal((await member.state()).ownerObligations.length, 0)
  await member.command('obligation.update', { agreementId: a.id, obligationId: monthly, action: 'confirm' }, { error: 'FORBIDDEN' })
  await owner.command('obligation.update', { agreementId: a.id, obligationId: pending, action: 'done' }, { error: 'STATUS' })
  for (const id of [monthly, quarterly, annual, waived, pending]) await owner.command('obligation.update', { agreementId: a.id, obligationId: id, action: 'confirm' })
  await owner.command('obligation.update', { agreementId: a.id, obligationId: refused, action: 'reject' })
  await owner.command('obligation.update', { agreementId: a.id, obligationId: refused, action: 'done' }, { error: 'STATUS' })
  const assigned = (await member.state()).notifications.items.filter(x => x.agreement_id === a.id)
  assert.equal(assigned.length, 1)
  assert.ok(assigned.every(x => x.kind === 'assignment' && x.email_status === 'suppressed' && x.link.endsWith('/terms')))
  await member.command('notification.preferences', { inApp: true, email: true, digest: false, timezone: 'America/New_York' })
  assert.deepEqual((await stranger.state()).ownerObligations.map(x => x.id), [pending])
  assert.deepEqual((await member.state()).ownerObligations.map(x => x.id).sort(), [monthly].sort())
  const fixtureIds = [monthly, quarterly, annual, waived, refused, pending]
  for (const [person, id] of [[owner, quarterly], [member, monthly], [stranger, pending], [annualOwner, annual], [waiverOwner, waived]]) {
    assert.deepEqual((await person.state()).ownerObligations.filter(x => fixtureIds.includes(x.id)).map(x => x.id), [id])
  }
  let s = await owner.state(), row = id => s.obligations.find(x => x.id === id)
  assert.equal(row(monthly).lifecycle_status, 'upcoming')
  const staleVersion = s.agreements.find(x => x.id === a.id).version
  await owner.command('obligation.update', { agreementId: a.id, version: staleVersion, obligationId: quarterly, action: 'done' })
  await owner.command('obligation.update', { agreementId: a.id, version: staleVersion, obligationId: monthly, action: 'done', note: 'Evidence' }, { error: 'STALE' })
  s = await owner.state()
  assert.equal(row(monthly).status, 'confirmed')
  assert.deepEqual(s.obligations.filter(x => x.series_id === quarterly).map(x => [x.due_date, x.lifecycle_status]), [['2026-01-31','done'], ['2026-04-30','upcoming']])
  const nextQuarter = s.obligations.find(x => x.series_id === quarterly && x.status === 'confirmed')
  const concurrent = await Promise.all([0, 1].map(() => owner.request('/api/locket/commands', { method: 'POST', body: { commandId: crypto.randomUUID(), type: 'obligation.update', payload: { agreementId: a.id, obligationId: nextQuarter.id, action: 'done' } } })))
  assert.deepEqual(concurrent.map(x => x.status).sort(), [200, 409])
  s = await owner.state()
  assert.deepEqual(s.obligations.filter(x => x.series_id === quarterly).map(x => [x.due_date, x.lifecycle_status]), [['2026-01-31','done'], ['2026-04-30','done'], ['2026-07-31','upcoming']])
  await stranger.command('obligation.update', { agreementId: a.id, obligationId: monthly, action: 'done', note: 'Not my assignment' }, { error: 'FORBIDDEN' })
  await member.command('obligation.update', { agreementId: a.id, obligationId: monthly, action: 'done' }, { error: 'EVIDENCE' })
  await member.command('obligation.update', { agreementId: a.id, obligationId: waived, action: 'waive', reason: 'Not authorized' }, { error: 'FORBIDDEN' })
  await owner.command('obligation.update', { agreementId: a.id, obligationId: waived, action: 'waive' }, { error: 'INVALID' })
  await h.setTime(Date.parse('2026-01-31T05:00:00Z'))
  s = await member.state(); assert.equal(row(monthly).lifecycle_status, 'due')
  await h.setTime(Date.parse('2026-02-01T05:00:00Z'))
  s = await member.state(); assert.equal(row(monthly).lifecycle_status, 'missed')
  await owner.command('obligation.update', { agreementId: a.id, obligationId: waived, action: 'waive', reason: 'Owner records this occurrence as waived; no contract amendment.' })
  await h.scheduled(Date.parse('2026-02-01T14:00:00Z'))
  await h.scheduled(Date.parse('2026-02-01T15:00:00Z'))
  assert.equal(h.mails.filter(x => x.subject === 'Overdue obligation in Locket' && x.to[0] === 'synthetic-locket-owner@example.test').length, 1)
  const reminder = h.mails.find(x => x.subject === 'Overdue obligation in Locket' && x.to[0] === 'synthetic-locket-owner@example.test')
  assert.ok(reminder.text.includes('/app#agreement/'))
  assert.ok(!reminder.text.includes('synthetic-locket-monthly'))
  const commandId = crypto.randomUUID(), payload = { agreementId: a.id, obligationId: monthly, action: 'done', note: 'Retained monthly report receipt' }
  const closed = await member.command('obligation.update', payload, { commandId })
  assert.deepEqual(await member.command('obligation.update', payload, { commandId }), closed)
  s = await owner.state()
  const feb = s.obligations.find(x => x.id === closed.nextId)
  assert.deepEqual([row(monthly).lifecycle_status, row(monthly).evidence_note, feb.due_date, feb.evidence_note, feb.recurrence_anchor], ['done','Retained monthly report receipt','2026-02-28',null,'2026-01-31'])
  assert.deepEqual([row(waived).lifecycle_status, row(waived).done_by, row(waived).waiver_reason], ['waived', ownerId, 'Owner records this occurrence as waived; no contract amendment.'])
  await owner.command('obligation.update', { agreementId: a.id, obligationId: annual, action: 'done' })
  s = await owner.state()
  assert.deepEqual(s.obligations.filter(x => x.series_id === annual).map(x => x.due_date).sort(), ['2024-02-29','2025-02-28'])
  await h.setTime(Date.parse('2026-02-28T15:00:00Z'))
  Object.assign(h.owner, await h.signIn('owner@example.test'))
  Object.assign(member, await h.signIn('synthetic-locket-owner@example.test'))
  await member.command('obligation.update', { agreementId: a.id, obligationId: feb.id, action: 'done', note: 'February receipt' })
  s = await owner.state()
  assert.deepEqual(s.obligations.filter(x => x.series_id === monthly).map(x => [x.due_date, x.lifecycle_status]).sort(), [['2026-01-31','done'], ['2026-02-28','done'], ['2026-03-31','upcoming']])
  assert.equal(s.obligations.filter(x => x.series_id === monthly && x.status === 'confirmed').length, 1)
  assert.ok(s.audit.some(x => x.action === 'obligation.waive' && x.actor_id === ownerId))
  await h.owner.command('access.set', { agreementId: a.id, operatorId: member.id, grant: 'revoke' })
  assert.deepEqual((await member.state()).ownerObligations, [])
  await member.command('obligation.update', { agreementId: a.id, obligationId: pending, action: 'done' }, { error: 'NOT_FOUND' })
  await h.owner.command('obligation.add', { agreementId: a.id, description: 'Cannot assign to former reader', ownerId: member.id, dueDate: '2026-03-31', recurrence: 'none', citation: { quote } }, { error: 'INVALID' })
  await h.setTime(Date.parse('2026-03-02T15:00:00Z'))
  Object.assign(h.owner, await h.signIn('owner@example.test'))
  const response = await owner.request('/api/locket/outcome-report?month=2026-02')
  assert.equal(response.status, 200)
  const outcome = await response.json(), january = outcome.months.find(x => x.month === '2026-01')
  assert.ok(january.figures.deadlinesMissed.evidence.some(x => x.recordId === monthly))
  assert.ok(january.figures.deadlinesMissed.evidence.some(x => x.recordId === waived))
  assert.ok(outcome.months.some(month => month.figures.deadlinesLate.evidence.some(x => x.recordId === monthly)))
  assert.ok(outcome.months.every(month => !month.figures.deadlinesLate.evidence.some(x => x.recordId === waived)))
  const exported = await (await owner.request('/api/locket/export')).json()
  assert.equal(exported.records.lk_obligations.filter(x => (x.series_id ?? x.id) === monthly).length, 3)
}
