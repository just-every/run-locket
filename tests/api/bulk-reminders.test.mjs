import test from 'node:test'
import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { installation } from './harness.mjs'
import { bulkAgreement, bulkClock, bulkFixture, bulkTerms } from './bulk-reminders-fixture.mjs'

const preview = (client, ids, ownerId) => client.command('renewal.bulk.preview', { agreementIds: ids, ownerId, offsets: [90, 60, 30, 7] })
test('RENEW-004 reviews 40 imported agreements, stores 34 current-term schedules, audits every outcome and never claims delivery', async t => {
  const h = await installation({ bindings: { TEST_NOW: String(bulkClock) } }); t.after(() => h.close())
  const fixture = await bulkFixture(h.owner)
  const ownerId = (await h.owner.state()).actor.id
  const p = await preview(h.owner, fixture.ids, ownerId)
  assert.equal(p.tracked.length, 34); assert.equal(p.skipped.length, 6)
  assert.deepEqual(p.skipped.map(r => r.agreementId).sort(), fixture.missing.sort())
  assert.ok(p.skipped.every(r => /Missing confirmed terms/.test(r.reason) && !r.deadlineAt && !r.reminders.length))
  for (const id of fixture.old) {
    const row = p.tracked.find(r => r.agreementId === id)
    assert.deepEqual([row.start, row.end, row.term, row.deadlineDate, row.deadlineAt], ['2026-03-01', '2027-02-28', 5, '2026-12-30', Date.parse('2026-12-31T04:59:59Z')])
    assert.ok(row.deadlineAt > bulkClock)
    assert.equal(new Date(row.reminders.find(r => r.offsetDays === 30).at).toISOString(), '2026-11-30T14:00:00.000Z')
    assert.equal(new Date(row.reminders.find(r => r.offsetDays === 90).at).toISOString(), '2026-10-01T13:00:00.000Z')
  }
  assert.equal((await h.owner.state()).reminderSchedules.length, 0)
  const commandId = randomUUID()
  const applied = await h.owner.command('renewal.bulk.apply', { previewId: p.id }, { commandId })
  assert.deepEqual(applied, { previewId: p.id, scheduled: 34, skipped: 6, deliveryStatus: 'not_delivered' })
  assert.deepEqual(await h.owner.command('renewal.bulk.apply', { previewId: p.id }, { commandId }), applied)
  await h.owner.command('renewal.bulk.apply', { previewId: p.id }, { error: 'STALE' })
  const s = await h.owner.state()
  assert.equal(s.reminderSchedules.length, 34)
  for (const r of s.reminderSchedules) {
    const reviewed = p.tracked.find(row => row.agreementId === r.agreement_id)
    assert.equal(r.owner_id, ownerId); assert.equal(r.deadline_at, reviewed.deadlineAt)
    assert.deepEqual(r.reminders, reviewed.reminders); assert.deepEqual(r.offsets, [90, 60, 30, 7])
    assert.equal(r.delivery_status, 'not_delivered'); assert.equal(r.schedule_status, 'scheduled')
    assert.equal(s.agreements.find(a => a.id === r.agreement_id).version, r.agreement_version)
  }
  for (const action of ['renewal.bulk.preview', 'renewal.bulk.apply']) {
    const events = s.audit.filter(e => e.action === action)
    assert.equal(events.length, 40)
    assert.ok(events.every(e => e.actor_id === ownerId && e.actor_role === 'owner' && e.at === bulkClock && e.agreement_id && e.summary))
  }
  assert.equal(s.terms.find(r => r.agreement_id === fixture.old[0] && r.key === 'end_date' && r.status === 'confirmed').value, '2023-02-28')
})

test('RENEW-004 rejects changed previews, wrong roles, hidden agreements and another actor’s preview; expired agreements are skipped', async t => {
  const h = await installation({ bindings: { TEST_NOW: String(bulkClock) } }); t.after(() => h.close())
  const ownerId = (await h.owner.state()).actor.id
  const approver = await h.invite('bulk-approver@example.test', 'approver')
  const viewer = await h.invite('bulk-viewer@example.test', 'viewer')
  const id = await bulkAgreement(h.owner, 'visible')
  const hidden = await bulkAgreement(h.owner, 'hidden', { restricted: true })
  const expired = await bulkAgreement(h.owner, 'expired', { terms: { ...bulkTerms, auto_renew: 'no' } })
  const expiredPreview = await preview(h.owner, [expired], ownerId)
  assert.equal(expiredPreview.tracked.length, 0); assert.equal(expiredPreview.skipped[0].reason, 'Expired')
  await viewer.command('renewal.bulk.preview', { agreementIds: [id], ownerId, offsets: [7] }, { error: 'FORBIDDEN' })
  await approver.command('renewal.bulk.preview', { agreementIds: [id, hidden], ownerId, offsets: [7] }, { error: 'NOT_FOUND' })
  await h.owner.command('renewal.bulk.preview', { agreementIds: [hidden], ownerId: viewer.id, offsets: [7] }, { error: 'INVALID' })
  const own = await preview(h.owner, [id], ownerId)
  await approver.command('renewal.bulk.apply', { previewId: own.id }, { error: 'NOT_FOUND' })
  const p = await preview(approver, [id], approver.id)
  await h.owner.command('term.propose', { agreementId: id, key: 'end_date', value: '2029-02-28', citation: { quote: 'Agreed terms.' } })
  await approver.command('renewal.bulk.apply', { previewId: p.id }, { error: 'STALE' })
  assert.equal((await h.owner.state()).reminderSchedules.length, 0)
  const accepted = await preview(approver, [id], approver.id)
  await approver.command('renewal.bulk.apply', { previewId: accepted.id })
  const hiddenPreview = await preview(h.owner, [hidden], ownerId)
  await h.owner.command('renewal.bulk.apply', { previewId: hiddenPreview.id })
  assert.deepEqual((await viewer.state()).reminderSchedules.map(r => r.agreement_id), [id])
  assert.ok((await h.owner.state()).audit.some(e => e.agreement_id === hidden && e.action === 'agreement.view'))
  await h.owner.command('access.set', { agreementId: hidden, operatorId: approver.id, grant: 'grant' })
  const ownerAccessPreview = await preview(h.owner, [hidden], approver.id)
  await h.owner.command('access.set', { agreementId: hidden, operatorId: approver.id, grant: 'revoke' })
  await h.owner.command('renewal.bulk.apply', { previewId: ownerAccessPreview.id }, { error: 'STALE' })
  assert.equal((await h.owner.state()).reminderSchedules.length, 2)
  const replayId = randomUUID(), replayPayload = { agreementIds: [id], ownerId, offsets: [7] }
  const demoted = await approver.command('renewal.bulk.preview', replayPayload, { commandId: replayId })
  await h.owner.command('role.set', { operatorId: approver.id, role: 'viewer' })
  await approver.command('renewal.bulk.apply', { previewId: demoted.id }, { error: 'FORBIDDEN' })
  await approver.command('renewal.bulk.preview', replayPayload, { commandId: replayId, error: 'FORBIDDEN' })
  await h.owner.command('renewal.bulk.preview', { agreementIds: [id], ownerId: 'absent', offsets: [7] }, { error: 'INVALID' })
  const signedOut = await h.request('/api/locket/commands', { method: 'POST', body: { commandId: randomUUID(), type: 'renewal.bulk.apply', payload: { previewId: own.id } } })
  assert.equal(signedOut.status, 401)
  const terminating = await bulkAgreement(h.owner, 'terminating', {terms:{...bulkTerms,effective_date:'2026-01-01',end_date:'2026-10-18',notice_days:'0'}})
  const renewal = (await h.owner.state()).renewals.find(r=>r.agreement_id===terminating)
  await h.owner.command('renewal.decide',{renewalId:renewal.id,decision:'terminate'})
  const notice = await h.owner.command('notice.prepare',{renewalId:renewal.id,recipient:'notices@supplier.example',body:'We give notice to terminate at the end of this term.'})
  await h.owner.command('notice.approve',{noticeId:notice.id})
  await h.owner.command('notice.sent',{noticeId:notice.id,method:'courier',sentAt:'2026-10-17T12:00:00Z'})
  await h.setTime(Date.parse('2026-10-19T12:00:00Z'))
  const terminated = await preview(h.owner,[terminating],ownerId)
  assert.equal(terminated.tracked.length,0)
  assert.equal(terminated.skipped[0].reason,'Terminated')
  const many=[id]
  for(let i=0;i<137;i++)many.push(await bulkAgreement(h.owner,`Unreviewed supplier ${i}`,{terms:{}}))
  const operation=await h.owner.command('renewal.bulk.start',{agreementIds:many,ownerId,offsets:[30,7]})
  let progress=await h.owner.command('renewal.bulk.next',{operationId:operation.id})
  assert.ok(progress.previewed>0&&progress.previewed<many.length)
  let resumed=(await h.owner.state()).reminderOperations.find(j=>j.id===operation.id)
  assert.equal(resumed.previewed,progress.previewed)
  while(progress.status==='previewing')progress=await h.owner.command('renewal.bulk.next',{operationId:operation.id})
  resumed=(await h.owner.state()).reminderOperations.find(j=>j.id===operation.id)
  assert.equal(resumed.tracked.length,1);assert.equal(resumed.skipped.length,many.length-1)
  progress=await h.owner.command('renewal.bulk.next',{operationId:operation.id,apply:true})
  assert.equal(progress.status,'applying')
  assert.ok(progress.processed>0&&progress.processed<many.length)
  assert.equal((await h.owner.state()).reminderOperations.find(j=>j.id===operation.id).processed,progress.processed)
  while(progress.status==='applying')progress=await h.owner.command('renewal.bulk.next',{operationId:operation.id,apply:true})
  assert.equal(progress.status,'done');assert.equal(progress.scheduled,1);assert.equal(progress.processed,many.length)
  const finalState=await h.owner.state()
  assert.ok(finalState.audit.some(e=>e.action==='renewal.bulk.start'&&e.actor_id===ownerId&&e.actor_role==='owner'&&e.summary.includes(String(many.length))))
  await h.owner.command('role.set',{operatorId:approver.id,role:'approver'})
  assert.deepEqual((await approver.state()).reminderOperations,[])
  assert.deepEqual((await viewer.state()).reminderOperations,[])
  assert.ok((await(await h.owner.request('/api/locket/export')).json()).records.lk_bulk_reminder_operations.some(j=>j.id===operation.id))


})
